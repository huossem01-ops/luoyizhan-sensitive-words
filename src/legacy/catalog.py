    for category, groups in CATALOG.items():
        records = []
        for spec in groups:
            for term in spec["terms"]:
                records.append({
                    "term": term,
                    "category": category,
                    "subcategory": spec["subcategory"],
                    "trigger_level": spec["trigger_level"],
                    "semantic_distance": spec["semantic_distance"],
                    "humor": spec["humor"],
                    "reason": (
                        f"属于“{spec['subcategory']}”语义，"
                        f"与“{category}”主题的关联距离为{spec['semantic_distance']}级"
                    ),
                    "tags": list(dict.fromkeys([category, spec["subcategory"], *spec["tags"]])),
                })
        per_category[category] = records

    width = max(map(len, per_category.values()))
    for index in range(width):
        for category in CATALOG:
            records = per_category[category]
            if index < len(records):
                yield records[index]
